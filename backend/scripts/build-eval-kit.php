<?php
declare(strict_types=1);

/**
 * build-eval-kit.php — regenerates eval-kit/ from backend/ (docs/REMAINING.md A6).
 *
 * eval-kit/ used to be a HAND-MAINTAINED parallel copy of parts of
 * backend/ — and it had already silently drifted: its own copy of
 * AiPrompts.php was missing 4 of the 8 prompt methods (confirmed while
 * researching this rebuild), and nothing would have caught that short of
 * reading both files side by side. This script makes eval-kit/ a
 * GENERATED artifact instead: every file it copies below always matches
 * backend/'s current, canonical version, so that class of drift becomes
 * structurally impossible rather than something to remember to check.
 *
 * What's intentionally NOT copied: `backend/services/ai/AiJobQueue.php`
 * and `backend/config/db.php` — eval-kit/ never touches the real
 * `ai_processing_log` queue or any database (a friend's run has no DB
 * access at all; results come back as files for the maintainer to insert
 * via AiEvaluationRunRepository afterward, same as A2's own flow).
 *
 * Usage (from backend/):
 *   php scripts/build-eval-kit.php
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit(1);
}

$backendDir = dirname(__DIR__);
$repoRoot = dirname($backendDir);
$evalKitDir = $repoRoot . '/eval-kit';

const GENERATED_BANNER = "<?php\n// GENERATED by backend/scripts/build-eval-kit.php — DO NOT HAND-EDIT.\n// Re-run that script after changing the corresponding backend/ file.\n\n";

/**
 * @param string[] $files backend-relative paths to copy verbatim into the
 *                        same relative path under eval-kit/, stamped with
 *                        a GENERATED banner for every .php file.
 */
function copyGenerated(string $backendDir, string $evalKitDir, array $files): void
{
    foreach ($files as $relative) {
        $src = $backendDir . '/' . $relative;
        $dest = $evalKitDir . '/' . $relative;
        if (!is_file($src)) {
            fwrite(STDERR, "Source not found, skipping: {$relative}\n");
            continue;
        }
        if (!is_dir(dirname($dest))) {
            mkdir(dirname($dest), 0777, true);
        }
        $contents = (string) file_get_contents($src);
        if (str_ends_with($relative, '.php')) {
            // Strip the source's own opening "<?php\n" (and any immediately
            // following declare(strict_types=1);) before re-stamping, so we
            // don't end up with two <?php openers.
            $contents = preg_replace('/^<\?php\s*/', '', $contents, 1);
            $contents = GENERATED_BANNER . 'declare(strict_types=1);' . "\n\n" . preg_replace('/^declare\(strict_types=1\);\s*/', '', $contents, 1);
        }
        file_put_contents($dest, $contents);
        echo "Wrote {$relative}\n";
    }
}

// PHP source: every AiPrompts/Ollama file, the eval scorer library, the
// generalized evaluation script, and the autoloader (fixed so
// eval-kit/'s own copy never needs a second hand edit either).
copyGenerated($backendDir, $evalKitDir, [
    'services/ai/AiPrompts.php',
    'services/ai/OllamaClient.php',
    'services/ai/OllamaException.php',
    'services/ai/OllamaUnavailableException.php',
    'services/ai/RegexRedactor.php',
    'services/eval/RedactionScorer.php',
    'services/eval/ExtractionScorer.php',
    'services/eval/ChecklistScorer.php',
    'scripts/ai-evaluate.php',
    'config/autoload.php',
]);

// Fixtures: the input dataset(s) a friend's run reads. NOT the
// checkpoint/results/log files ai-evaluate.php produces while running —
// those are the friend's own local run state, never part of the package
// they received (and already gitignored on the backend/ side for the
// same reason). eval-sms-prompts-v1.json and eval-threat-stats-v1.json
// were removed with sms_compose/threat_analysis (migration 0027).
$fixturesDir = $backendDir . '/fixtures';
if (!is_dir($evalKitDir . '/fixtures')) {
    mkdir($evalKitDir . '/fixtures', 0777, true);
}
foreach (['eval-incidents-v1.json', 'redaction-eval-sample.json'] as $fixture) {
    $src = $fixturesDir . '/' . $fixture;
    if (!is_file($src)) {
        fwrite(STDERR, "Fixture not found, skipping: {$fixture}\n");
        continue;
    }
    copy($src, $evalKitDir . '/fixtures/' . $fixture);
    echo "Wrote fixtures/{$fixture}\n";
}

echo "\neval-kit/ regenerated from backend/. Diff it against the previous version before committing if you want to see exactly what changed.\n";
