/**
 * passphrase.ts — provisions the SQLCipher passphrase for the local encrypted store.
 *
 * DECISION: a cryptographically-random passphrase is generated ON THE DEVICE at first run and persisted
 * app-privately. It is never derived from the user's password, and never fetched from the server.
 *
 * Why not server-issued: a brand-new install would be unable to capture ANYTHING until it had first
 * reached the workstation, contradicting offline-first capture. Why not derived from the password: it
 * is unavailable offline after login, and a password change would orphan the database.
 *
 * Stored with `@aparajita/capacitor-secure-storage`, whose Android implementation encrypts with AES-GCM
 * under a key generated by the Android Keystore before writing to SharedPreferences.
 * `localDatabase.ts` only ever asks for a `PassphraseProvider` and never cares how the secret is stored.
 *
 * Existing installs: a passphrase already written under the old @capacitor/preferences key is read
 * once, migrated into secure storage, and the old plaintext copy is removed, so an in-place install is
 * not locked out of its own already-encrypted database. A fresh install never touches the old storage.
 *
 * Consequence worth knowing: if this value is lost (app data cleared, uninstall), the local database is
 * unrecoverable. Device loss/uninstall is outside the application guarantee, and the server is
 * authoritative after reconciliation.
 */

import { Preferences } from '@capacitor/preferences';
import { SecureStorage } from '@aparajita/capacitor-secure-storage';

const PASSPHRASE_KEY = 'baranguard.dbPassphrase';
/** The pre-Keystore-upgrade key, kept only for the one-time migration read. */
const LEGACY_PREFERENCES_KEY = 'baranguard.dbPassphrase';

/** 32 random bytes, hex-encoded — 256 bits of entropy. */
function generatePassphrase(): string {
  const bytes = new Uint8Array(32);
  crypto.getRandomValues(bytes);
  return Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
}

/**
 * Returns this install's database passphrase, creating and persisting one
 * on first call. Suitable to pass directly to
 * `configureLocalDatabase()`.
 */
export async function getOrCreatePassphrase(): Promise<string> {
  const existing = await SecureStorage.getItem(PASSPHRASE_KEY);
  if (existing) return existing;

  // One-time migration path: an install that ran before the Keystore
  // upgrade has its passphrase sitting in plain @capacitor/preferences.
  // Move it into secure storage rather than generating a SECOND
  // passphrase, which would orphan the already-encrypted database.
  const legacy = await Preferences.get({ key: LEGACY_PREFERENCES_KEY });
  if (legacy.value) {
    await SecureStorage.setItem(PASSPHRASE_KEY, legacy.value);
    await Preferences.remove({ key: LEGACY_PREFERENCES_KEY });
    return legacy.value;
  }

  const passphrase = generatePassphrase();
  await SecureStorage.setItem(PASSPHRASE_KEY, passphrase);
  return passphrase;
}
